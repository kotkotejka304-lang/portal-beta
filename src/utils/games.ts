export const ALL_GAMES: Game[] = [...BUILT_IN_GAMES, ...CURATED_GAMES];

export function getGameByUrl(url: string): Game | undefined {
  return ALL_GAMES.find((g) => g.url === url || (g.isBuiltIn && url.startsWith(g.url)));
}

export function getGameById(id: string): Game | undefined {
  return ALL_GAMES.find((g) => g.id === id);
}

export function isGameEmbedSupported(game: Game): boolean {
  if (game.isBuiltIn) return true;
  return game.embedSupported === true;
}

export interface AlternateEmbedOption {
  title: string;
  url: string;
  note: string;
  badge?: string;
}

/**
 * Checks whether an in-frame alternative is available for a blocked gaming URL.
 * Automatically maps games like Cut the Rope, 2048, Snake, Breakout, Connect 4, etc.
 * to their verified embeddable or native Portal counterparts.
 */
export function getAlternateEmbeddableUrl(url: string): AlternateEmbedOption | null {
  if (!url) return null;
  const lower = url.toLowerCase();

  // Cut the Rope
  if (lower.includes('cut-the-rope') || lower.includes('cuttherope')) {
    return {
      title: 'Cut the Rope Classic',
      url: 'https://yell0wsuit.github.io/cuttherope-h5dx/index.html',
      note: 'A verified open HTML5 edition of Cut the Rope is available. It plays directly in this frame with accurate candy-cutting physics and zero embedding blocks.',
      badge: 'Verified HTML5 Edition',
    };
  }

  // Flappy Bird
  if (lower.includes('flappy') || lower.includes('floppy')) {
    return {
      title: 'Flappy Bird Canvas',
      url: 'https://nebezb.github.io/floppybird/',
      note: 'A verified open-source HTML5 canvas release of Flappy Bird is available that runs smoothly in an embedded frame.',
      badge: 'Verified In-Frame Play',
    };
  }

  // 2048
  if (lower.includes('2048')) {
    return {
      title: 'Quantum 2048',
      url: 'portal://game/2048',
      note: 'Portal includes a native, built-in Quantum 2048 game with full iPad touch swipe gestures, high-score tracking, and zero load latency.',
      badge: 'Built-in Native Game',
    };
  }

  // Snake
  if (lower.includes('snake') || lower.includes('slither')) {
    return {
      title: 'Neon Snake',
      url: 'portal://game/snake',
      note: 'Portal includes an original Neon Snake game with responsive iPad touch D-pad, smooth acceleration, and score persistence.',
      badge: 'Built-in Native Game',
    };
  }

  // Breakout
  if (
    lower.includes('breakout') ||
    lower.includes('brick-breaker') ||
    lower.includes('arkanoid')
  ) {
    return {
      title: 'Liquid Breakout',
      url: 'portal://game/breakout',
      note: 'Portal includes an original Liquid Breakout game with paddle touch drag, sound synthesis, and particle sparks.',
      badge: 'Built-in Native Game',
    };
  }

  // Connect Four
  if (
    lower.includes('connect4') ||
    lower.includes('connect-four') ||
    lower.includes('four-in-a-row') ||
    lower.includes('four-in-row')
  ) {
    return {
      title: 'Quantum Four',
      url: 'portal://game/connect4',
      note: 'Portal includes a built-in Quantum Four game supporting both local 2-player pass-and-play and smart bot AI.',
      badge: 'Built-in Native Game',
    };
  }

  // Minesweeper
  if (lower.includes('minesweeper')) {
    return {
      title: 'Neon Minesweeper',
      url: 'portal://game/minesweeper',
      note: 'Portal includes a built-in Neon Minesweeper with touch Flag/Reveal mode toggle and customizable grids.',
      badge: 'Built-in Native Game',
    };
  }

  // Sliding 15 puzzle
  if (
    lower.includes('sliding') ||
    lower.includes('15-puzzle') ||
    lower.includes('fifteen')
  ) {
    return {
      title: 'Liquid 15 Puzzle',
      url: 'portal://game/sliding',
      note: 'Portal includes a built-in 15 puzzle with guaranteed solvable shuffles and moves counter.',
      badge: 'Built-in Native Game',
    };
  }

  // Reaction / Reflex
  if (
    lower.includes('reaction') ||
    lower.includes('humanbenchmark') ||
    lower.includes('reflex')
  ) {
    return {
      title: 'Chrono Reaction',
      url: 'portal://game/reaction',
      note: 'Portal includes a built-in Chrono Reaction benchmark measuring reaction speed down to the millisecond.',
      badge: 'Built-in Native Game',
    };
  }

  // Chrome Dino / T-Rex Runner
  if (lower.includes('chromedino') || lower.includes('t-rex') || lower.includes('dinosaur')) {
    return {
      title: 'Chrome T-Rex Dino Runner',
      url: 'https://wayou.github.io/t-rex-runner/',
      note: 'A verified embed-safe HTML5 canvas edition of the Chrome T-Rex runner that plays inside Portal.',
      badge: 'Verified In-Frame Play',
    };
  }

  // Tetris
  if (lower.includes('tetris')) {
    return {
      title: 'Hextris Hexagonal Puzzle',
      url: 'https://hextris.io/',
      note: 'A verified embed-safe fast-paced puzzle inspired by Tetris that plays seamlessly inside Portal.',
      badge: 'Verified In-Frame Play',
    };
  }

  // Check matching game in ALL_GAMES by originalUrl
  const matched = ALL_GAMES.find(
    (g) =>
      g.embedSupported &&
      ((g.originalUrl && url.startsWith(g.originalUrl)) || (g.url && url.startsWith(g.url)))
  );
  if (matched) {
    return {
      title: matched.title,
      url: matched.url,
      note: `A verified embed-safe version of ${matched.title} is available inside Portal.`,
      badge: 'Verified In-Frame Play',
    };
  }

  return null;
}

